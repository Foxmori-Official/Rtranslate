/** A safe, localizable diagnostic suffix; raw provider errors are deliberately discarded. */
export function userErrorText(error: unknown, language: string, parser = false): string {
  const safe = parser ? parserUserError(error) : asUserError(error)
  const lang = resolveUiLang(language)
  const message = fmt(ERROR_MESSAGES[lang][safe.errorCode], safe.errorParams as Record<string, number>)
  const status = safe.errorParams.status ? `; HTTP ${safe.errorParams.status}` : ''
  return `${message} [${safe.errorCode}${status}]`
}

